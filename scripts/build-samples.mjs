#!/usr/bin/env node
// Copies the executa's sample alerts + code into the UI bundle (bundle/samples.js),
// so the window's sample buttons always match what the tests use.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const samples = join(root, "executas/nightcall/samples");
const code = (name) =>
  readdirSync(join(samples, name, "src"))
    .sort()
    .map((f) => `// file: src/${f}\n` + readFileSync(join(samples, name, "src", f), "utf8"))
    .join("\n");

// The two alerts used by the Anna review team, verbatim.
const out = {
  regex: {
    alert: '{"title":"escape-string-regexp fails on unescaped slash","service":"web","error":"SyntaxError: Invalid regular expression: /a/b(/: Unterminated group"}',
    code: code("search"),
  },
  checkout: {
    alert: JSON.stringify(
      { title: "TypeError: Cannot read properties of undefined (reading 'id')", service: "checkout-api", stack: "at getUser (src/user.js:42:18)\n at handler (src/checkout.js:17:5)" },
    ),
    code: code("checkout"),
  },
};
writeFileSync(join(root, "bundle/samples.js"), `/* generated by scripts/build-samples.mjs */\nexport const SAMPLES = ${JSON.stringify(out, null, 2)};\n`);
console.log("bundle/samples.js written");
